import matplotlib.pyplot as plt
import numpy as np

"""### Part 1a - Shear Diagram

You will create your shear diagram in the code block below.

"""

L = 6 # in feet
Ra = 170 # in lb
Rb = 410 # in lb
P1 = 100 # in lb
q1 = 120 # in lb/ft
q2 = 120 # in lb/ft

x = np.linspace(0, L, 500) # Creates the array.
V = np.zeros_like(x) # This function will create a list of zeros with the same length as x.

for i in range(len(x)): # This for loop is a little complicated but essentially it loops through all of x.
  if x[i] < 2: # If x is less than 2, then the formula underneath will perform.
    V[i] = Ra - (q1 * x[i])
  elif 2 <= x[i] <= 4: # If x is between 2 and 4, then the formula underneath will perform.
    V[i] = Ra - (q1 * 2) - P1
  elif x[i] > 4: # If x is greater than 4, then the formula underneath will perform.
    V[i] = Ra - (q1 * 2) - P1 + Rb - (q2 * (x[i] - 4))

plt.plot(x, V, color = 'blue') # Everything for the graph to be made.
plt.axhline(0, color='black', linewidth=1.2, linestyle='-') # Adds the x-axis reference line
plt.xlabel('x (ft)')
plt.ylabel('V (lb)')
plt.title('Shear Diagram')
plt.fill_between(x, V, color = 'yellow') # Adds colors underneath the line.
plt.show()

"""### Part 1b - Moment Diagram

You will create your moment diagram in the code block below.
"""

L = 6 # in feet
Ra = 170 # in lb
Rb = 410 # in lb
P1 = 100 # in lb
q1 = 120 # in lb/ft
q2 = 120 # in lb/ft

x = np.linspace(0, L, 500) # Creates the array.

M = np.zeros_like(x) # Creates a list of zeros equal to the length of x.

for i in range(len(x)): # Loops through every value in x.
  if x[i] < 2: # There are three if statements throughout, and depending on what the value of x is, a certain function will perform.
    M[i] = (Ra * x[i]) - (q1 * ((x[i] ** 2) / 2))
  elif 2 < x[i] < 4:
    M[i] = (Ra * x[i]) - (q1 * 2 * (x[i] - 1)) - (P1 * (x[i] - 2))
  elif x[i] > 4:
    M[i] = (Ra * x[i]) - (q1 * 2 * (x[i] - 1)) - (P1 * (x[i] - 2)) + (Rb * (x[i] - 4)) - (q2 * (x[i] - 4) * ((x[i] - 4) / 2))

plt.plot(x, M, color = 'orange') # This creates the graph.
plt.axhline(0, color='black', linewidth=1.2, linestyle='-') # Adds the x-axis reference line.
plt.fill_between(x, M, color = 'yellow') # Adds color underneath the lines.
plt.title('Moment Diagram')
plt.xlabel('x (ft)')
plt.ylabel('M (lb-ft)')
plt.show()

