plt.plot(x_fremont, y_fremont_west, label='Fremont Bridge West Sidewalk')
plt.plot(x_fremont, y_fremont_east, label='Fremont Bridge East Sidewalk')

plt.title('Fremont Bridge Bicycle Count') # Add the titles and the labels.
plt.xlabel('Date & Time')
plt.ylabel('Bicycle Count')

